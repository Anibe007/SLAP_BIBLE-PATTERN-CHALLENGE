/**
 * Deterministic hash generator for a name string.
 * Ensures the exact same name generates the same unique index every time,
 * while different names produce completely different unique quotes.
 */
export function getNameHash(name = '') {
  if (!name || typeof name !== 'string') return 0;
  const clean = name.trim().toLowerCase();
  if (!clean) return 0;
  let hash = 0;
  for (let i = 0; i < clean.length; i++) {
    hash = (hash * 31 + clean.charCodeAt(i)) >>> 0;
  }
  return hash;
}

