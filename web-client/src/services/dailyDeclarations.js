/**
 * Returns today's declaration based on the day of the year AND the declarant name.
 * Different names produce unique scripture quotes on the same day, and every day
 * each name rotates automatically to their next unique quote!
 */
export function getDailyDeclaration(date = new Date(), name = '', offset = 0) {
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date - startOfYear;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay) + offset;
  
  const nameHash = getNameHash(name);
  const total = DAILY_SCRIPTURE_DECLARATIONS.length;
  
  // Combine calendar day + name hash to guarantee a unique quote per name daily
  const index = Math.abs(dayOfYear + nameHash) % total;
  const baseDecl = DAILY_SCRIPTURE_DECLARATIONS[index];
  
  const cleanName = (name || '').trim();
  const personalizedText = cleanName ? personalizeDeclarationText(baseDecl.text, cleanName) : baseDecl.text;
  
  return {
    ...baseDecl,
    rawText: baseDecl.text,
    text: personalizedText,
    declarantName: cleanName,
    dayOfYear,
    dateString: date.toLocaleDateString(undefined, { month: 'short', day: 'numeric' })
  };
}

/**
 * Get a specific declaration by day offset and optional name
 */
export function getDeclarationByOffset(offset = 0, name = '', baseDate = new Date()) {
  const targetDate = new Date(baseDate);
  targetDate.setDate(targetDate.getDate() + offset);
  return getDailyDeclaration(targetDate, name, 0);
}
